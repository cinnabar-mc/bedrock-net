// Command go-oracle emits synthetic batch vectors from Cinnabar's pinned Go codec.
package main

import (
	"bytes"
	"fmt"
	"os"

	"github.com/sandertv/gophertunnel/minecraft/protocol/packet"
)

// main reports failures once, at the command boundary.
// With the argument "serve" it instead answers length-prefixed requests on stdin.
func main() {
	run := run
	if len(os.Args) == 2 && os.Args[1] == "serve" {
		run = func() error { return serve(os.Stdin, os.Stdout) }
	}
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// run emits source constants; the packet bodies are synthetic and contain no account data.
func run() error {
	packets := [][]byte{{2, 0, 0, 0, 0}, {9, 3, 'h', 'e', 'y'}}
	if _, err := fmt.Fprintln(os.Stdout, "// Generated by tools/go-oracle. Synthetic data; do not edit."); err != nil {
		return err
	}
	for _, algorithm := range []packet.Compression{packet.FlateCompression, packet.SnappyCompression, packet.NopCompression} {
		var wire bytes.Buffer
		encoder := packet.NewEncoder(&wire)
		encoder.EnableCompression(algorithm, 12)
		if err := encoder.Encode(packets); err != nil {
			return fmt.Errorf("encode oracle batch: %w", err)
		}
		if err := emit(fmt.Sprintf("GO_BATCH_%d", algorithm.EncodeCompression()), wire.Bytes()); err != nil {
			return err
		}
		wire.Reset()
		encoder.EnableCompression(algorithm, 0)
		withEmpty := [][]byte{{}, packets[0], {}, packets[1], {}}
		if err := encoder.Encode(withEmpty); err != nil {
			return fmt.Errorf("encode empty-entry oracle batch: %w", err)
		}
		decoder := packet.NewDecoder(bytes.NewReader(wire.Bytes()))
		decoder.DisableBatchPacketLimit()
		decoder.EnableCompression(algorithm, 0)
		decoded, err := decoder.Decode()
		if err != nil {
			return fmt.Errorf("decode empty-entry oracle batch: %w", err)
		}
		if len(decoded) != len(packets) {
			return fmt.Errorf("empty-entry oracle changed packet count")
		}
		for index, value := range decoded {
			if !bytes.Equal(value, packets[index]) {
				return fmt.Errorf("empty-entry oracle changed packet order or contents")
			}
		}
		if err := emit(fmt.Sprintf("GO_BATCH_EMPTY_%d", algorithm.EncodeCompression()), wire.Bytes()); err != nil {
			return err
		}
	}
	var key [32]byte
	for index := range key {
		key[index] = byte(index)
	}
	var encrypted bytes.Buffer
	encoder := packet.NewEncoder(&encrypted)
	encoder.EnableCompression(packet.NopCompression, 0)
	encoder.EnableEncryption(key)
	for index := range 3 {
		encrypted.Reset()
		if err := encoder.Encode(packets); err != nil {
			return fmt.Errorf("encode encrypted oracle batch: %w", err)
		}
		if err := emit(fmt.Sprintf("GO_ENCRYPTED_%d", index), encrypted.Bytes()); err != nil {
			return err
		}
	}
	return nil
}

// emit writes one Rust byte-slice constant.
func emit(name string, value []byte) error {
	if _, err := fmt.Fprintf(os.Stdout, "pub const %s: &[u8] = &[", name); err != nil {
		return err
	}
	for _, b := range value {
		if _, err := fmt.Fprintf(os.Stdout, "0x%02x,", b); err != nil {
			return err
		}
	}
	_, err := fmt.Fprintln(os.Stdout, "];")
	return err
}
